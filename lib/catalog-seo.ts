export const categoryPath = (id: string) => '/products/category/' + id;
export const catalogCategories = categories.filter(category => category.id !== 'all')
  .filter(category => products.some(product => product.category === category.id))
  .map(category => ({...category, ...content[category.id]}));
export const findCatalogCategory = (id: string) => catalogCategories.find(category => category.id === id);
