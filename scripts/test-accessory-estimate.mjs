import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import ts from 'typescript';
const source=await readFile(new URL('../lib/accessory-estimate.ts',import.meta.url),'utf8');
const compiled=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ES2022}}).outputText;
const {calculateCord,calculateFasteners,calculateRoofBlocks,calculatePackages}=await import('data:text/javascript;base64,'+Buffer.from(compiled).toString('base64'));
const cord=overrides=>({geometry:{kind:'ties',ties:100,tieLength:.6},allowance:.1,extraLength:0,wastePercent:5,coilLength:100,...overrides});
const fastener=overrides=>({geometry:{kind:'count',sheets:20,supportsPerSheet:4,screwsPerSupport:3},extraCount:12,wastePercent:5,packSize:100,...overrides});
const blocks=overrides=>({runs:[{length:5.2,count:12}],blockLength:2,extraCount:0,wastePercent:5,packSize:1,...overrides});

const tieExample=calculateCord(cord());
assert.equal(tieExample.baseLength,70);
assert.equal(tieExample.requiredLength,73.5);
assert.equal(tieExample.cutPlan.totalCoils,1);
assert.equal(tieExample.cutPlan.reservePieces,5);
const fragmented=calculateCord(cord({geometry:{kind:'ties',ties:3,tieLength:.6},allowance:0,wastePercent:0,coilLength:1}));
assert.equal(fragmented.minimumCoils,2);
assert.equal(fragmented.cutPlan.totalCoils,3,'three separate 0.6 m cuts cannot come from two 1 m coils');
const wholeReserve=calculateCord(cord({geometry:{kind:'ties',ties:2,tieLength:.6},allowance:0,wastePercent:5,coilLength:1}));
assert.equal(wholeReserve.cutPlan.reservePieces,1);
assert.equal(wholeReserve.cutPlan.totalCoils,3,'reserve must fit a full additional tie');
const exact=calculateCord(cord({geometry:{kind:'ties',ties:3,tieLength:.1},allowance:0,wastePercent:0,coilLength:.3}));
assert.equal(exact.minimumCoils,1);
assert.equal(exact.cutPlan.totalCoils,1,'decimal length boundary must be exact');
const uncuttable=calculateCord(cord({geometry:{kind:'runs',runs:[{length:101,count:1}]},allowance:0,coilLength:100}));
assert.equal(uncuttable.cutPlan,undefined);
const spaced=calculateCord(cord({geometry:{kind:'spaced',runs:[{length:1,count:2}],spacing:.3,tieLength:.5},allowance:0,wastePercent:0}));
assert.equal(spaced.pieces,10,'each independent run includes both endpoints');
assert.equal(calculateCord(cord({geometry:{kind:'spaced',runs:[{length:.3,count:1}],spacing:.1,tieLength:.5},allowance:0,wastePercent:0})).pieces,4);
assert.equal(calculateCord(cord({geometry:{kind:'runs',runs:[{length:2,count:3},{length:3,count:2}]},allowance:.2,wastePercent:0,coilLength:5})).baseLength,13);
assert.equal(calculateCord(cord({geometry:{kind:'ties',ties:2,tieLength:.5},allowance:0,wastePercent:0,coilLength:2,extraLength:1})).cutPlan.totalCoils,1,'free extra length can use the uncut coil tail');

assert.deepEqual(calculateFasteners(fastener()),{baseCount:240,extraCount:12,reserveCount:13,requiredCount:265,packs:3,purchaseCount:300,surplusCount:35});
assert.equal(calculateFasteners(fastener({geometry:{kind:'spacing',runs:[{length:.3,count:2},{length:.301,count:1}],spacing:.1,screwsPerPoint:2},extraCount:0,wastePercent:0,packSize:1})).baseCount,26);
assert.equal(calculatePackages(100,0,0,100).packs,1);
assert.equal(calculatePackages(100,0,.001,100).packs,2,'a genuine fractional reserve needs one whole extra piece');
const roof=calculateRoofBlocks(blocks());
assert.equal(roof.baseCount,36);
assert.equal(roof.purchaseCount,38);
assert.equal(roof.rows[0].lastPieceLength,1.2);
assert.equal(roof.offcutLength,9.6);
assert.equal(calculateRoofBlocks(blocks({runs:[{length:.3,count:1}],blockLength:.1,wastePercent:0})).baseCount,3);
assert.equal(calculateRoofBlocks(blocks({runs:[{length:.301,count:1}],blockLength:.1,wastePercent:0})).baseCount,4);
assert.equal(calculateRoofBlocks(blocks({runs:[{length:2.1,count:2},{length:1.9,count:2}],wastePercent:0})).baseCount,6,'each row is rounded independently; offcuts are not silently reused');
for(const bad of [{coilLength:0},{allowance:-1},{wastePercent:51},{extraLength:NaN},{geometry:{kind:'ties',ties:1.5,tieLength:1}},{geometry:{kind:'ties',ties:1,tieLength:.0001}},{geometry:{kind:'runs',runs:[]}},{geometry:{kind:'spaced',runs:[{length:1,count:1}],spacing:0,tieLength:.5}}])assert.throws(()=>calculateCord(cord(bad)));
for(const bad of [{packSize:0},{packSize:1.5},{extraCount:-1},{geometry:{kind:'count',sheets:2,supportsPerSheet:3,screwsPerSupport:1.5}},{geometry:{kind:'spacing',runs:[{length:1,count:1}],spacing:0,screwsPerPoint:1}}])assert.throws(()=>calculateFasteners(fastener(bad)));
for(const bad of [{runs:[]},{runs:[{length:0,count:1}]},{runs:[{length:2,count:1.2}]},{blockLength:0},{wastePercent:Infinity}])assert.throws(()=>calculateRoofBlocks(blocks(bad)));
for(let i=1;i<=200;i++){
 const input=cord({geometry:{kind:'ties',ties:i,tieLength:(i%35+1)/10},coilLength:4+i%11,allowance:.1,wastePercent:i%21,extraLength:.1});
 const result=calculateCord(input),plan=result.cutPlan;
 assert(plan&&plan.totalCoils>=result.minimumCoils);
 assert(plan.purchasedLength+1e-8>=result.requiredLength);
 const pieceLength=input.geometry.tieLength+input.allowance;
 const capacity=Math.floor((input.coilLength+1e-9)/pieceLength);
 assert(plan.totalCoils*capacity>=i+plan.reservePieces,'coils can physically yield all full ties including reserve');
 const count=calculateFasteners(fastener({geometry:{kind:'count',sheets:i,supportsPerSheet:i%9+1,screwsPerSupport:i%5+1},packSize:i%90+1,wastePercent:i%21}));
 assert.equal(count.purchaseCount% (i%90+1),0);
 assert(count.purchaseCount>=count.requiredCount);
 assert(count.purchaseCount-(i%90+1)<count.requiredCount,'minimal complete package count');
 const roof=calculateRoofBlocks(blocks({runs:[{length:i/10,count:i%4+1}],blockLength:1.2,wastePercent:i%21}));
 assert(roof.rows[0].perRun*1.2+1e-9>=i/10);
 assert(roof.rows[0].lastPieceLength>0&&roof.rows[0].lastPieceLength<=1.2);
 assert(roof.purchaseCount>=roof.baseCount);
}
console.log('PASS: cord cut capacity and whole-piece reserves, exact decimal boundaries, counted/spaced fasteners, independent roof rows, packs, invalid inputs and 200 coverage invariants.');
